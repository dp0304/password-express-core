"""AI 通行证 (AI Pass) Python SDK for custom agents.

Agents discover resources, request structured operations, wait for the user's approval on a
trusted device, and read permitted results — without ever seeing raw credentials.

>>> from aipass import Client
>>> with Client(key_file="~/.aipass/connections/my-agent.key") as client:  # doctest: +SKIP
...     op = client.request_operation(resource_id, "postgres.query_view", {...}, idempotency_key="report-2026-10-30")
...     if op["status"] == "approval_required":
...         op = client.wait_for_operation(op["operation_id"])
"""

